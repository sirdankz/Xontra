static const uint8_t *glyph(char c)
{
    size_t i;

    if (c >= 'a' && c <= 'z')
        c = (char)(c - 'a' + 'A');
    for (i = 0; i < sizeof(kFont) / sizeof(kFont[0]); i++)
        if (kFont[i].c == c)
            return kFont[i].rows;
    return NULL;                /* a space, or what the font has not */
}

void osd_text(uint32_t *fb, int w, int h, int x, int y,
              const char *text, uint32_t colour, int scale)
{
    int i, row, col, dx, dy;
    if (!fb || !text || scale < 1 || scale > 4) return;
    for (i = 0; text[i]; ++i) {
        const uint8_t *g = glyph(text[i]);
        if (!g) continue;
        for (row = 0; row < GLYPH_H; ++row)
            for (col = 0; col < GLYPH_W; ++col) {
                if (!(g[row] & (0x10 >> col))) continue;
                for (dy = 0; dy < scale; ++dy)
                    for (dx = 0; dx < scale; ++dx) {
                        int px = x + (i * ADVANCE + col) * scale + dx;
                        int py = y + row * scale + dy;
                        if (px >= 0 && px < w && py >= 0 && py < h)
                            fb[py * w + px] = colour;
                    }
            }
    }
}

void osd_show(Osd *o, const char *text, int frames)
{
    strncpy(o->text, text, sizeof(o->text) - 1);
    o->text[sizeof(o->text) - 1] = 0;
    o->frames = frames;
}

void osd_draw(Osd *o, uint32_t *fb, int w, int h)
{
    int len, x0, y0, x, y, i;

    if (o->frames <= 0)
        return;
    o->frames--;
    len = (int)strlen(o->text);
    x0 = (w - (len * ADVANCE - 1)) / 2;
    y0 = h - 8 - 24;            /* above the bottom lines a television hides */

    /* the band: the picture under it darkened to a quarter */
    for (y = y0 - 3; y < y0 + GLYPH_H + 3; y++)
        for (x = x0 - 4; x < x0 + len * ADVANCE + 3; x++)
            if (x >= 0 && x < w && y >= 0 && y < h)
            {
                uint32_t p = fb[y * w + x];

                fb[y * w + x] = 0xFF000000u | ((p >> 2) & 0x3F3F3Fu);
            }
    for (i = 0; i < len; i++)
    {
        const uint8_t *g = glyph(o->text[i]);

        if (!g)
            continue;
        for (y = 0; y < GLYPH_H; y++)
            for (x = 0; x < GLYPH_W; x++)
            {
                int px = x0 + i * ADVANCE + x, py = y0 + y;

                if (!(g[y] & (0x10 >> x)) || px < 0 || px >= w || py < 0 || py >= h)
                    continue;
                fb[py * w + px] = 0xFFFFFFFFu;
            }
    }
}
